import React, { useEffect, useMemo, useState } from 'react';
import './App.css';
import { parsePrompt } from './lib/prompt/parse';
import { generateErekirSiliconLayout } from './lib/layout/erekirSilicon';
import { encodeSchematicBase64, encodeSchematicBinary } from './lib/schematic/encoder';
import { decodeSchematicBinary, fromBase64 } from './lib/schematic/decoder';
import { PreviewGrid } from './components/PreviewGrid';

const examplePrompts = [
  'compact three silicon factories for Erekir',
  '5 silicon factories, Erekir, small footprint',
  'Erekir silicon 2',
];

const AppMindustry: React.FC = () => {
  const [prompt, setPrompt] = useState(examplePrompts[0]);
  const [error, setError] = useState<string | null>(null);
  const [base64, setBase64] = useState<string>('');
  const [tileCount, setTileCount] = useState<number>(0);
  const [info, setInfo] = useState<{ totalCost: Record<string, number>; powerUse: number } | null>(null);
  const [tiles, setTiles] = useState<ReturnType<typeof generateErekirSiliconLayout>['schematic']['tiles']>([]);

  const generate = () => {
    setError(null);
    try {
      const spec = parsePrompt(prompt);
      if (spec.planet !== 'erekir' || spec.product !== 'silicon') {
        throw new Error('MVP supports only Erekir silicon for now.');
      }
      const { schematic, info } = generateErekirSiliconLayout({
        planet: 'erekir',
        target: 'silicon',
        count: spec.count,
        compact: spec.compact,
      });
      const b64 = encodeSchematicBase64(schematic);
      // Round-trip decode to sanity-check structure
      const decoded = decodeSchematicBinary(fromBase64(b64));
      setTileCount(decoded.tiles.length);
      setTiles(schematic.tiles);
      setInfo({ totalCost: info.totalCost, powerUse: info.powerUse });
      setBase64(b64);
    } catch (e: any) {
      setError(e?.message ?? String(e));
    }
  };

  useEffect(() => {
    // Auto-generate on first load for the example prompt
    generate();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const download = () => {
    try {
      const bytes = encodeSchematicBinary({
        width: computeBounds(tiles).width,
        height: computeBounds(tiles).height,
        tiles,
        tags: { name: 'Generated', description: 'Generated by MVP' },
      });
      // Ensure Blob is constructed from a plain ArrayBuffer to satisfy TS DOM overloads.
      const clone = new Uint8Array(bytes); // own ArrayBuffer
      const blob = new Blob([clone.buffer], { type: 'application/octet-stream' });
      const a = document.createElement('a');
      a.href = URL.createObjectURL(blob);
      a.download = 'build.msch';
      a.click();
      URL.revokeObjectURL(a.href);
    } catch (e) {
      console.error(e);
    }
  };

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(base64);
    } catch (e) {
      console.error(e);
    }
  };

  const bounds = useMemo(() => computeBounds(tiles), [tiles]);

  return (
    <div style={{ maxWidth: 980, margin: '0 auto', padding: 16 }}>
      <h1>Mindustry Schematic Builder (MVP)</h1>
      <p>Describe a build in plain language. Example prompts:</p>
      <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap', marginBottom: 8 }}>
        {examplePrompts.map((p) => (
          <button key={p} onClick={() => setPrompt(p)} style={{ padding: '6px 10px' }}>
            {p}
          </button>
        ))}
      </div>
      <div style={{ display: 'flex', gap: 8 }}>
        <input
          value={prompt}
          onChange={(e) => setPrompt(e.target.value)}
          style={{ flex: 1, padding: 8, fontSize: 16 }}
          placeholder="e.g., compact three silicon factories for Erekir"
        />
        <button onClick={generate} style={{ padding: '8px 12px' }}>
          Generate
        </button>
      </div>
      {error && <div style={{ color: 'red', marginTop: 8 }}>{error}</div>}
      <div style={{ marginTop: 16, display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 16 }}>
        <div>
          <h3>Preview</h3>
          <PreviewGrid tiles={tiles} />
          <div style={{ marginTop: 8, fontSize: 14 }}>
            <div>
              Bounds: {bounds.width} x {bounds.height} tiles
            </div>
            <div>Tiles: {tileCount}</div>
            <div>
              Power balance: {info?.powerUse ? `-${info.powerUse.toFixed(1)} power` : '0'} (consumption only)
            </div>
            <div>
              Cost:{' '}
              {info
                ? Object.entries(info.totalCost)
                    .map(([k, v]) => `${k}:${v}`)
                    .join(', ')
                : '—'}
            </div>
          </div>
        </div>
        <div>
          <h3>Export</h3>
          <textarea value={base64} readOnly rows={12} style={{ width: '100%', fontFamily: 'monospace' }} />
          <div style={{ display: 'flex', gap: 8, marginTop: 8 }}>
            <button onClick={copy}>Copy base64</button>
            <button onClick={download}>Download .msch</button>
          </div>
          <p style={{ fontSize: 12, color: '#666' }}>
            The base64 starts with bXNjaA… which is the ASCII header "msch" plus version, then zlib-compressed body.
          </p>
        </div>
      </div>
      <p style={{ marginTop: 24, fontSize: 12, color: '#666' }}>
        Preview uses simple colored blocks (no game sprites). Mindustry content © Anuke; sprites are GPL. This site does
        not redistribute sprites.
      </p>
    </div>
  );
};

function computeBounds(tiles: { x: number; y: number }[]) {
  if (!tiles.length) return { width: 0, height: 0 };
  const xs = tiles.map((t) => t.x);
  const ys = tiles.map((t) => t.y);
  const minX = Math.min(...xs);
  const maxX = Math.max(...xs);
  const minY = Math.min(...ys);
  const maxY = Math.max(...ys);
  return { width: maxX - minX + 1, height: maxY - minY + 1 };
}

export default AppMindustry;

