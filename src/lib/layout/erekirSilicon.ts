import type { Schematic, Tile } from '../schematic/types';
import { estimatePowerUsage, getBlockSpec, sumCosts } from '../blocks/blocks';

export interface SiliconRequest {
  planet: 'erekir';
  target: 'silicon';
  count: number; // number of furnaces
  compact?: boolean;
  inputs?: 'north' | 'south' | 'east' | 'west';
  outputs?: 'south' | 'north' | 'east' | 'west';
}

// Place N silicon-arc-furnace in a row with shared input (sand, graphite) ducts at top,
// an output duct at bottom, and beam-nodes linking power.
export function generateErekirSiliconLayout(req: SiliconRequest): {
  schematic: Schematic;
  info: {
    blockCount: Record<string, number>;
    totalCost: Record<string, number>;
    powerUse: number;
  };
} {
  const n = Math.max(1, Math.min(12, Math.floor(req.count)));
  const gap = req.compact ? 1 : 2; // spacing between furnaces (center-to-center) minus size

  const arc = getBlockSpec('silicon-arc-furnace')!;
  const duct = getBlockSpec('duct')!;
  const ductRouter = getBlockSpec('duct-router')!;
  const beamNode = getBlockSpec('beam-node')!;

  const tiles: Tile[] = [];

  // Arrange arc furnaces in a horizontal row centered around (0, 0).
  const step = arc.size + gap;
  const startX = -((n - 1) * step) / 2;
  for (let i = 0; i < n; i++) {
    const x = Math.round(startX + i * step);
    const y = 0;
    tiles.push({ block: arc.name, x, y, rotation: 0, config: null });

    // Power beam node behind each furnace (above).
    tiles.push({ block: beamNode.name, x, y: y + Math.ceil(arc.size / 2) + 1, rotation: 0, config: null });
  }

  // Link power beam nodes in a line: add additional nodes between large gaps, simple linear.
  // For MVP, the beam nodes are adjacent per-furnace; Mindustry will autolink nearby nodes when placed.

  // Build input ducts (top): two parallel lines for sand (left) and graphite (right)
  // Position: one tile above the beam node line.
  const inputY = Math.ceil(arc.size / 2) + 2;
  const leftX = Math.round(startX - Math.floor(arc.size / 2));
  const rightX = Math.round(startX + (n - 1) * step + Math.floor(arc.size / 2));
  // Top bus (one line) from leftX to rightX for sand
  for (let x = leftX; x <= rightX; x++) {
    tiles.push({ block: duct.name, x, y: inputY, rotation: 0, config: null });
    // second parallel line for graphite above it
    tiles.push({ block: duct.name, x, y: inputY + 1, rotation: 0, config: null });
  }
  // Drop ducts into each furnace via routers centered above each furnace
  for (let i = 0; i < n; i++) {
    const x = Math.round(startX + i * step);
    const entryY = inputY - 1; // router between bus and furnace top
    tiles.push({ block: ductRouter.name, x, y: entryY, rotation: 2, config: null });
    tiles.push({ block: ductRouter.name, x, y: entryY + 2, rotation: 2, config: null });
  }

  // Output duct line below furnaces
  const outputY = -Math.ceil(arc.size / 2) - 1;
  for (let x = leftX; x <= rightX; x++) {
    tiles.push({ block: duct.name, x, y: outputY, rotation: 0, config: null });
  }

  // Compute bounding box
  const bounds = computeBounds(tiles);

  const schem: Schematic = {
    width: bounds.width,
    height: bounds.height,
    tiles,
    tags: {
      name: `${n}x Erekir Silicon Arc Furnace`,
      description: 'Generated by Mindustry Schematic Builder MVP',
      planet: 'erekir',
      product: 'silicon',
      count: String(n),
    },
  };

  const blockCount: Record<string, number> = {};
  for (const t of tiles) blockCount[t.block] = (blockCount[t.block] ?? 0) + 1;

  const totalCost = sumCosts(tiles.map((t) => t.block));
  const powerUse = estimatePowerUsage(tiles.map((t) => t.block));

  return { schematic: schem, info: { blockCount, totalCost, powerUse } };
}

function computeBounds(tiles: Tile[]): { minX: number; minY: number; maxX: number; maxY: number; width: number; height: number } {
  let minX = Infinity,
    minY = Infinity,
    maxX = -Infinity,
    maxY = -Infinity;
  for (const t of tiles) {
    const spec = getBlockSpec(t.block);
    const size = spec?.size ?? 1;
    const half = Math.floor(size / 2);
    const left = t.x - half;
    const right = t.x + half;
    const bottom = t.y - half;
    const top = t.y + half;
    minX = Math.min(minX, left);
    minY = Math.min(minY, bottom);
    maxX = Math.max(maxX, right);
    maxY = Math.max(maxY, top);
  }
  const width = Math.max(1, Math.round(maxX - minX + 1));
  const height = Math.max(1, Math.round(maxY - minY + 1));
  return { minX, minY, maxX, maxY, width, height };
}

